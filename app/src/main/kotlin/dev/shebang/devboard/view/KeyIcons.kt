        "M5.5 11 H7.5 A4.5 4.5 0 0 0 16.5 11 H18.5 A6.5 6.5 0 0 1 13 17.4 V19 H11 V17.4 A6.5 6.5 0 0 1 5.5 11 Z " +
        "M9 19.5 H15 V21.5 H9 Z"

    /**
     * The Shebang mark, # and ! interlocked (the app icon's, in one colour), for the #! key. Generated by
     * tools/shebang_mark.py key from the same geometry as res/drawable/ic_launcher_foreground.xml.
