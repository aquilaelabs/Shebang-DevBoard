    private const val SHEBANG = "M11.79 4.40 L9.39 21.20 A1.4 1.4 0 0 1 6.61 20.80 L9.01 4.00 A1.4 1.4 0 0 1 11.79 4.40 Z M3.20 8.40 L14.75 8.40 L14.42 11.20 L3.20 11.20 A1.4 1.4 0 0 1 3.20 8.40 Z M19.96 8.40 L20.80 8.40 A1.4 1.4 0 0 1 20.80 11.20 L19.56 11.20 Z M2.40 14.00 L14.10 14.00 L13.78 16.80 L2.40 16.80 A1.4 1.4 0 0 1 2.40 14.00 Z M19.17 14.00 L20.00 14.00 A1.4 1.4 0 0 1 20.00 16.80 L18.77 16.80 Z M16.60 1.00 L20.00 1.00 L17.80 16.60 L14.80 16.60 Z M13.60 21.00 A2 2 0 1 1 17.60 21.00 A2 2 0 1 1 13.60 21.00 Z"

    /** A face: a ring, two block cursors for eyes, and a smile (the ring is cut out: even-odd). */
    private const val EMOJI = "M3 12 A9 9 0 1 0 21 12 A9 9 0 1 0 3 12 Z M5 12 A7 7 0 1 0 19 12 A7 7 0 1 0 5 12 Z " +
        "M8.5 8.5 H10.5 V11 H8.5 Z M13.5 8.5 H15.5 V11 H13.5 Z " +
